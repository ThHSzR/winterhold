package br.eng.thsouza.winterhold

import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Test
import org.junit.runner.RunWith
import java.net.HttpURLConnection
import java.net.ServerSocket
import java.net.URL
import java.util.concurrent.CopyOnWriteArrayList
import javax.net.ssl.HttpsURLConnection
import javax.net.ssl.SSLContext
import javax.net.ssl.X509TrustManager
import java.security.cert.X509Certificate

@RunWith(AndroidJUnit4::class)
class SecurityDeliveryIntegrationTest {
    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private val context = instrumentation.targetContext
    private val password = "Instrumentation-only-password-2026"
    private var cookie = ""
    private fun onMain(block: () -> Unit) = instrumentation.runOnMainSync(block)
    private fun request(path: String, body: JSONObject? = null, authenticated: Boolean = true, port: Int = 8790): Pair<Int, String> {
        val connection = URL("${if (port == 8792) "https" else "http"}://127.0.0.1:$port$path").openConnection() as HttpURLConnection
        if (connection is HttpsURLConnection) {
            // Pin the certificate generated by this target app, never trust all certificates.
            val expected = WebTls.context().let {
                java.security.KeyStore.getInstance("AndroidKeyStore").apply { load(null) }.getCertificate("winterhold-web-tls-v1").encoded
            }
            val trust = object : X509TrustManager {
                override fun getAcceptedIssuers() = emptyArray<X509Certificate>()
                override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit
                override fun checkServerTrusted(chain: Array<out X509Certificate>, authType: String?) {
                    require(chain[0].encoded.contentEquals(expected))
                }
            }
            connection.sslSocketFactory = SSLContext.getInstance("TLS").apply { init(null, arrayOf(trust), null) }.socketFactory
            connection.hostnameVerifier = javax.net.ssl.HostnameVerifier { host, _ -> host == "127.0.0.1" }
        }
        connection.connectTimeout = 5000; connection.readTimeout = 10000
        if (authenticated) connection.setRequestProperty("Cookie", cookie)
        if (body != null) {
            connection.requestMethod = "POST"; connection.doOutput = true
            connection.setRequestProperty("X-Winterhold-Request", "1")
            connection.setRequestProperty("Content-Type", "application/json")
            connection.outputStream.use { it.write(body.toString().toByteArray()) }
        }
        return try {
            val code = connection.responseCode
            if (path.endsWith("/login") && code == 200) cookie = connection.getHeaderField("Set-Cookie").substringBefore(';')
            code to (if (code < 400) connection.inputStream else connection.errorStream).bufferedReader().use { it.readText() }
        } finally { connection.disconnect() }
    }
    private fun action(vararg values: Pair<String, Any>): JSONObject = JSONObject().apply { values.forEach { put(it.first, it.second) } }
    private fun login() = request("/api/v1/login", action("username" to "device-tests", "password" to password), false)
    private fun await(check: () -> Boolean) {
        val deadline = System.currentTimeMillis() + 20_000
        while (System.currentTimeMillis() < deadline) { if (check()) return; Thread.sleep(100) }
        fail("Condition timed out")
    }
    @org.junit.Before fun setup() {
        onMain {
            DemoCentral.ensureStarted(context)
            DemoCentral.webUsers!!.users.firstOrNull { it.username == "device-tests" }?.let { DemoCentral.webUsers!!.delete(it.id) }
            DemoCentral.webUsers!!.add("Device tests", "device-tests", password)
        }
        assertEquals(200, login().first)
    }
    @org.junit.After fun cleanup() {
        onMain { DemoCentral.webUsers!!.users.firstOrNull { it.username == "device-tests" }?.let { DemoCentral.webUsers!!.delete(it.id) } }
    }
    @Test fun tlsSessionsRevocationAndNoWebAccountManagement() {
        assertEquals(401, request("/api/v1/state", authenticated = false).first)
        assertEquals(200, request("/api/v1/state", port = 8792).first)
        assertEquals(404, request("/api/v1/users").first)
        assertEquals(400, request("/api/v1/action", action("type" to "addWebUser", "username" to "bad")).first)
        val snapshot = request("/api/v1/state").second
        assertFalse(snapshot.contains("accounts_v2")); assertFalse(snapshot.contains(password))
        val users = DemoCentral.webUsers!!
        val id = users.users.first { it.username == "device-tests" }.id
        onMain { users.revoke(id) }
        assertEquals(401, request("/api/v1/state").first)
        assertEquals(200, login().first)
        onMain { users.resetPassword(id, password + "-changed") }
        assertEquals(401, request("/api/v1/state").first)
        assertEquals(401, login().first)
        onMain { users.resetPassword(id, password) }
        assertEquals(200, login().first)
        assertEquals(200, request("/api/v1/logout", JSONObject()).first)
        assertEquals(401, request("/api/v1/state").first)
        repeat(5) { assertEquals(401, users.login("device-tests", "wrong", "rate-test-peer").first) }
        assertEquals(429, users.login("device-tests", password, "rate-test-peer").first)
    }
    @Test fun fiveRoomsSendAutomaticallyNormalizeAndRecordMissingConfiguration() {
        val store = DemoCentral.store
        lateinit var saved: String
        val settings = DeliverySettings(context)
        val oldUrl = settings.bridgeUrl; val oldToken = settings.bridgeToken
        val messages = CopyOnWriteArrayList<JSONObject>()
        val server = ServerSocket(0, 8, java.net.InetAddress.getByName("127.0.0.1"))
        val receiver = Thread {
            while (!server.isClosed) runCatching {
                server.accept().use { socket ->
                    val reader = java.io.DataInputStream(socket.getInputStream())
                    var length = 0
                    while (true) {
                        val line = reader.readLine() ?: break
                        if (line.isEmpty()) break
                        if (line.startsWith("Content-Length:", true)) length = line.substringAfter(':').trim().toInt()
                    }
                    val body = ByteArray(length); reader.readFully(body)
                    messages.add(JSONObject(String(body, Charsets.UTF_8)))
                    socket.getOutputStream().write("HTTP/1.1 202 Accepted\r\nContent-Length: 22\r\nConnection: close\r\n\r\n{\"status\":\"submitted\"}".toByteArray())
                }
            }
        }.apply { isDaemon = true; start() }
        try {
            onMain {
                saved = store.savedJson()
                store.contacts.clear(); store.simulationRunning = false
                store.contacts.add(DemoContact(id = "mock-recipient", name = "Mock only", role = "Test", metrics = Metric.entries.toSet(),
                    channels = setOf(Channel.WHATSAPP, Channel.EMAIL) +
                        (if (context.checkSelfPermission(android.Manifest.permission.SEND_SMS) != android.content.pm.PackageManager.PERMISSION_GRANTED) setOf(Channel.SMS) else emptySet()),
                    phone = "+19999999999", email = "test@example.invalid"))
                settings.bridgeUrl = "http://127.0.0.1:${server.localPort}"; settings.bridgeToken = "mock-only-token-32-characters-long"
            }
            assertEquals(400, request("/api/v1/action", action("type" to "mode", "value" to "demo")).first)
            assertEquals(200, request("/api/v1/action", action("type" to "mode", "value" to "demo", "acknowledgeRealDelivery" to true)).first)
            onMain { store.simulationRunning = false }
            var expected = 0
            store.demoEnvironments.values.toList().forEach { profile ->
                fun reading(temperature: Float) = request("/api/v1/action", action("type" to "setDemoReading", "id" to profile.deviceId,
                    "temperature" to temperature, "humidity" to (profile.humidityMin + profile.humidityMax) / 2,
                    "voltage" to (profile.voltageMin + profile.voltageMax) / 2))
                reading((profile.temperatureMin + profile.temperatureMax) / 2)
                // Existing demo incidents can normalize first. Count only deliveries after a fresh breach.
                await { messages.size >= expected }
                Thread.sleep(150)
                expected = messages.size
                assertEquals(200, reading(profile.temperatureMax + 1).first)
                expected++; await { messages.size == expected }
                reading(profile.temperatureMax + 2); Thread.sleep(150); assertEquals(expected, messages.size)
                reading((profile.temperatureMin + profile.temperatureMax) / 2)
                expected++; await { messages.size == expected }
            }
            assertTrue(messages.size >= 10)
            assertTrue(messages.all { it.getString("message").contains("[SIMULADO]") })
            assertTrue(messages.any { it.getString("message").contains("normalizada") })
            assertEquals(messages.size, messages.map { it.getString("id") }.distinct().size)
            val deliveries = JSONObject(request("/api/v1/state").second).getJSONArray("deliveries")
            assertTrue((0 until deliveries.length()).any { deliveries.getJSONObject(it).getString("status").startsWith("blocked:") })
        } finally {
            server.close(); receiver.join(2000)
            onMain { store.restoreJson(saved); settings.bridgeUrl = oldUrl; settings.bridgeToken = oldToken }
        }
    }
}
